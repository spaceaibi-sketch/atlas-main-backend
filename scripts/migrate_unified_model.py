#!/usr/bin/env python3
"""Safe, backed-up transition to canonical raw_items / relationships / summary.

Usage:
  python3 scripts/migrate_unified_model.py --db FILE --dry-run
  python3 scripts/migrate_unified_model.py --db FILE --apply
  python3 scripts/migrate_unified_model.py --db FILE --verify

Never deletes originals: legacy News/SEC staging tables remain active until all
writers, dashboards and admin jobs use the new schema. This is an intermediate
compatibility migration, NOT authorization to drop old tables or source files.
Every News, filing and SEC item is copied with its entire original row in JSON.
"""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
from pathlib import Path
import sqlite3
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from scripts import legacy_unified_model as unified_model


def report(db):
    n={r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    print('Legacy counts:',{name: db.execute('SELECT COUNT(*) FROM '+name).fetchone()[0]
           for name in ('companies','news','forms','items','news_company_relations') if name in n})
    if 'raw_items' in n:
        print('Unified raw counts:',unified_model.integrity_counts(db))
        print('Unified relationship count:',db.execute('SELECT COUNT(*) FROM relationships').fetchone()[0])
    print('Summary:', 'summary' if 'summary' in n else 'company_mobile_summary' if 'company_mobile_summary' in n else 'not initialized')


def prepare_legacy_summary_rename(db):
    """Retire ONLY generated summary triggers before SQLite renames their table.

    SQLite reparses every trigger during ALTER TABLE RENAME. Older Atlas mobile
    triggers contain table-qualified references to company_mobile_summary in
    nested CTEs. Renaming with them installed can fail with
    'error in trigger atlas_mob_comp_ai after rename: no such column: ...'.
    They are regenerated by upgrade_summary() in the very same transaction.
    No user-defined or non-mobile trigger is silently deleted.
    """
    existing={r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    if 'company_mobile_summary' not in existing:
        return
    if 'summary' in existing:
        raise RuntimeError('Both company_mobile_summary and summary exist; reconcile before migrating')
    triggers=db.execute("SELECT name,sql FROM sqlite_master WHERE type='trigger'").fetchall()
    dropped=[]
    for name,_ in triggers:
        if name.startswith('atlas_mob_'):
            db.execute('DROP TRIGGER "'+name.replace('"','""')+'"')
            dropped.append(name)
    # SQLite rewrites other table-linked triggers/views on rename. Refuse
    # unrelated SQL referencing the obsolete table rather than corrupt its
    # semantics by guessing a replacement.
    dependents=db.execute("""SELECT type,name FROM sqlite_master
      WHERE type IN ('trigger','view') AND instr(lower(coalesce(sql,'')),
        'company_mobile_summary')>0 ORDER BY type,name""").fetchall()
    if dependents:
        raise RuntimeError('Unmigrated schema dependencies on company_mobile_summary: '
                           +', '.join(f'{kind}:{name}' for kind,name in dependents)
                           + '. No changes committed; inspect these definitions first.')
    print(f'Removed {len(dropped)} generated atlas_mob_ triggers before summary rename; '
          'the summary migration recreates them in this transaction.')


def migration(db):
    if not unified_model.available(db):
        raise RuntimeError('Cannot migrate incomplete main backend schema')
    prepare_legacy_summary_rename(db)
    unified_model.backfill(db)
    # Rename the actual MATERIALIZED table, retaining all rows, columns, indexes
    # and existing triggers. Never create a second summary with duplicated values.
    existing={r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    if 'company_mobile_summary' in existing:
        if 'summary' in existing:
            raise RuntimeError('Both mobile summary and summary tables exist; manual reconciliation needed')
        db.execute('ALTER TABLE company_mobile_summary RENAME TO summary')
    else:
        if 'summary' not in existing:
            # The canonical schema needs a summary, even if the old migration
            # has not been run. Use the existing author's summary schema.
            from dashboard.mobile_summary import SCHEMA
            for statement in SCHEMA.split(';'):
                if statement.strip():db.execute(statement)
    # Consolidate and refresh materialized summary from the same writer data.
    # The historic mobile-impact migration is part of this single transaction.
    from scripts.migrate_mobile_impact_summary import validate as check_summary, migrate as upgrade_summary
    upgrade_summary(db,check_summary(db))
    unified_model.install_mirror_triggers(db)
    # The unified relationships table is now authoritative for historical
    # cumulative calculations. Retire the redundant per-legacy-table triggers
    # (without dropping their historical record columns or any data).
    for (name,) in db.execute("SELECT name FROM sqlite_master WHERE type='trigger' "
                              "AND name LIKE 'atlas_cumulative_%'").fetchall():
        db.execute('DROP TRIGGER "'+name+'"')
    unified_model.validate(db)


def run(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--db',required=True,type=Path)
    a=p.add_mutually_exclusive_group(required=True)
    a.add_argument('--dry-run',action='store_true')
    a.add_argument('--apply',action='store_true')
    a.add_argument('--verify',action='store_true')
    args=p.parse_args(argv)
    path=args.db.expanduser().resolve(strict=True)
    with sqlite3.connect(path.as_uri()+'?mode=ro',uri=True) as db:
        if db.execute('PRAGMA integrity_check').fetchone()[0]!='ok':
            raise RuntimeError('Source database fails SQLite integrity check')
        if not unified_model.available(db):
            raise RuntimeError('Missing source tables; check the selected writer-owned database')
        report(db)
        if args.dry_run:
            print('DRY RUN — no database changes, no files removed')
            return
        if args.verify:
            unified_model.validate(db)
            print('Verification: PASS')
            return
    backup=path.with_name(path.name+'.before-unified-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')+'.bak')
    with sqlite3.connect(path,timeout=60) as src,sqlite3.connect(backup) as dst:
        src.execute('PRAGMA busy_timeout=60000')
        src.backup(dst)
        if dst.execute('PRAGMA integrity_check').fetchone()[0]!='ok':
            raise RuntimeError('Failed to verify backup; migration cancelled')
    print('FULL BACKUP:',backup)
    with sqlite3.connect(path,timeout=60,isolation_level=None) as db:
        db.execute('PRAGMA busy_timeout=60000')
        db.execute('PRAGMA foreign_keys=ON')
        db.execute('BEGIN IMMEDIATE')
        try:
            migration(db)
            db.execute('COMMIT')
        except BaseException:
            db.execute('ROLLBACK')
            raise
        report(db)
        print('Migration/verification: PASS. Legacy staging tables preserved for active writers.')
        print('No source files or legacy data were deleted.')

if __name__=='__main__':
    try:run()
    except (RuntimeError,ValueError,OSError,sqlite3.Error) as e:
        print('FAILED:',e,file=sys.stderr);sys.exit(1)
